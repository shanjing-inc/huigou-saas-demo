import { randomUUID } from "node:crypto";
import { mkdir, rename, rm, writeFile } from "node:fs/promises";
import { dirname } from "node:path";
import { fileURLToPath } from "node:url";
import { listenHost } from "./http.mjs";

export const miniappConfigPath = fileURLToPath(new URL("../miniprogram/packages/rebate/config/backend.js", import.meta.url));

export function listenAddress(env) {
    const host = listenHost(env);
    const port = Number(env.DEMO_PORT || 8787);
    if (!Number.isSafeInteger(port) || port < 1 || port > 65535) {
        throw new Error("DEMO_PORT must be a valid port.");
    }
    return { host, port, baseUrl: `http://${host}:${port}` };
}

export async function writeMiniappConfig(address, destination = miniappConfigPath) {
    await mkdir(dirname(destination), { recursive: true });
    const temporary = `${destination}.${randomUUID()}.tmp`;
    try {
        // Only the public address goes into the miniapp; never serialize env.
        await writeFile(temporary, `// Generated by pnpm dev / pnpm backend. Do not edit.\nmodule.exports = ${JSON.stringify({ BACKEND_BASE: address.baseUrl })};\n`, { flag: "wx" });
        await rename(temporary, destination);
    } finally {
        await rm(temporary, { force: true });
    }
}
